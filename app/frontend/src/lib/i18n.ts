// State management
let currentLocale: Locale = 'en';
const i18nListeners: Set<() => void> = new Set();

function notifyI18nListeners() {
  i18nListeners.forEach((fn) => fn());
}

export function subscribeI18n(fn: () => void) {
  i18nListeners.add(fn);
  return () => i18nListeners.delete(fn);
}

export function getLocale(): Locale {
  return currentLocale;
}

export function isRTL(): boolean {
  return currentLocale === 'ar';
}

export function setLocale(locale: Locale): void {
  if (locales.includes(locale)) {
    currentLocale = locale;
    localStorage.setItem('atlasphere_locale', locale);
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = locale;
    notifyI18nListeners();
  }
}

export function t(key: string): string {
  return messages[currentLocale]?.[key] || messages['en']?.[key] || key;
}

// Detect browser language on init
function detectLocale(): Locale {
  const saved = localStorage.getItem('atlasphere_locale') as Locale | null;
  if (saved && locales.includes(saved)) return saved;

  // Default language is always English unless user explicitly changes it
  return 'en';
}

// React hook to re-render on locale change
export function useI18nRerender() {
  const [, setTick] = useState(0);
  useEffect(() => {
    return subscribeI18n(() => setTick((t) => t + 1));
  }, []);
}

